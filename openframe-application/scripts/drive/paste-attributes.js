async page => {
  await page.setViewportSize({ width: 1600, height: 950 });
  await page.reload(); await page.waitForFunction(() => !!window.videoEditor);
  await page.locator(".create-card").click(); await page.locator(".timeline-panel").waitFor();
  await page.locator(".project-name").click(); await page.locator(".project-name-input").fill("__QA_20261016_attributes"); await page.locator(".project-name-input").press("Enter");
  await page.evaluate(() => {
    const api = window.videoEditor, track_id = api.project().tracks[0].id;
    api.exec("add_color_clip", { color: "#7fbbd0", start: 0, duration: 2, track_id });
    api.exec("add_color_clip", { color: "#663030", start: 4, duration: 2, track_id });
    const [a, b] = api.project().tracks[0].clips; window.__attributeIds = { a: a.id, b: b.id };
    api.exec("set_param", { clip_ids: [a.id], path: "adjust.exposure", value: 20 });
    api.exec("set_param", { clip_ids: [a.id], path: "transform.scale", value: 1.5 });
    api.exec("add_effect", { clip_id: a.id, type: "blur" });
    api.select([a.id]);
  });
  const details = {};
  await page.getByRole("button", { name: "Copy attributes", exact: true }).click();
  await page.evaluate(() => window.videoEditor.select([window.__attributeIds.b]));
  await page.getByRole("button", { name: "Paste attributes…", exact: true }).click();
  await page.getByRole("checkbox", { name: "Transform, crop and opacity", exact: true }).uncheck();
  await page.getByRole("checkbox", { name: "Effects and effect animation", exact: true }).uncheck();
  details.audioUnavailable = { ok: await page.getByRole("checkbox", { name: "Volume, pan, mute, fades and EQ", exact: true }).isDisabled() };
  await page.screenshot({ path: "scratch/paste-attributes-desktop.png", animations: "disabled" });
  await page.getByRole("button", { name: "Paste selected attributes", exact: true }).click();
  details.onlyColorAndNoCompaction = { ok: await page.evaluate(() => { const c = window.videoEditor.project().tracks[0].clips[1]; return c.adjust.exposure === 20 && c.transform.scale === 1 && c.effects.length === 0 && c.start === 120; }) };
  await page.evaluate(() => window.videoEditor.action("undo"));
  details.undo = { ok: await page.evaluate(() => window.videoEditor.project().tracks[0].clips[1].adjust.exposure === 0) };
  await page.evaluate(() => { const api = window.videoEditor; api.exec("add_effect", { clip_id: window.__attributeIds.b, type: "posterize" }); });
  await page.getByRole("button", { name: "Paste attributes…", exact: true }).click();
  await page.getByRole("checkbox", { name: "Replace existing effects", exact: true }).check();
  await page.getByRole("button", { name: "Paste selected attributes", exact: true }).click();
  details.replaceEffects = { ok: await page.evaluate(() => { const [a,b] = window.videoEditor.project().tracks[0].clips; return b.effects.length === 1 && b.effects[0].type === "blur" && b.effects[0].id !== a.effects[0].id && b.transform.scale === 1.5; }) };
  await page.getByRole("button", { name: "Paste attributes…", exact: true }).click();
  await page.setViewportSize({ width: 1100, height: 680 });
  details.narrowFit = { ok: await page.locator(".editor-dialog").evaluate((el) => el.scrollWidth <= el.clientWidth + 1 && el.getBoundingClientRect().bottom <= innerHeight) };
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.evaluate(() => { const api = window.videoEditor; api.exec("update_track", { track_id: api.project().tracks[0].id, locked: true }); });
  await page.getByRole("button", { name: "Paste attributes…", exact: true }).click();
  details.lockRespected = { ok: await page.getByRole("button", { name: "Paste selected attributes", exact: true }).isDisabled() };
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  return { ok: Object.values(details).every((d) => d.ok), details };
};
